// Global state
let currentLang = 'ko';

function setLanguage(lang) {
    if (!translations.nav_home[lang]) lang = 'ko';
    currentLang = lang;
    localStorage.setItem('nh_autoshop_lang', lang);

    // Update all DOM elements with data-i18n
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations[key] && translations[key][lang] !== undefined) {
            const translatedText = translations[key][lang];
            const icons = Array.from(el.querySelectorAll(':scope > i'));

            if (icons.length === 1) {
                const isIconFirst = el.firstElementChild && el.firstElementChild.tagName === 'I';
                if (isIconFirst) {
                    el.innerHTML = icons[0].outerHTML + ' ' + translatedText;
                } else {
                    el.innerHTML = translatedText + ' ' + icons[0].outerHTML;
                }
            } else if (icons.length > 1) {
                const firstIcon = icons[0];
                const lastIcon = icons[icons.length - 1];
                el.innerHTML = firstIcon.outerHTML + ' ' + translatedText + ' ' + lastIcon.outerHTML;
            } else {
                el.textContent = translatedText;
            }
        }
    });

    // Update HTML lang attribute
    document.documentElement.lang = lang;

    // Update switcher UI buttons if present
    document.querySelectorAll('.lang-switcher-btn').forEach(btn => {
        btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });

    // Update modal active option card
    document.querySelectorAll('.lang-opt-card').forEach(card => {
        card.classList.toggle('active', card.getAttribute('data-lang') === lang);
    });
}
